// Saves translations of the example (seed) content into server/tr-seed.js, so the demo board reads well
// in Korean and English even if the free translation services are busy. Run: node scripts/seed-translations.mjs
// Keeps what is already saved; only missing texts are translated. Uses the same free services as the app.
import { writeFileSync } from 'node:fs'
import { seedDb } from '../server/seed.js'
import saved from '../server/tr-seed.js'
import { translate } from '../server/translate.js'

const db = seedDb(Date.now())
const texts = new Set()
const add = (s) => s && s.trim() && texts.add(s)
for (const q of db.questions) [q.title, q.body, ...q.answers.map((a) => a.body)].forEach(add)
for (const p of db.posts) [p.title, p.body, p.meetup?.place, ...p.comments.map((c) => c.body)].forEach(add)
for (const g of db.groups) g.messages.forEach((m) => add(m.body))
for (const e of db.events) [e.title, e.body, e.place].forEach(add)

const all = [...texts]
console.log(all.length, 'texts,', all.join('').length, 'characters')
// Texts already in the target language are saved as-is (no call). Rough check: Hangul = Korean;
// plain ASCII with common English words = English.
const isKo = (t) => /[가-힣]/.test(t)
const isEn = (t) => !/[^ -~’—–…\n]/.test(t.replace(/\p{Extended_Pictographic}|\uFE0F/gu, '')) && /\b(the|you|i|is|to|and|for|my|me|in|it|can|do|of|anyone|where|how)\b/i.test(t)
const same = { ko: isKo, en: isEn }
const out = { ...saved }
for (const to of (process.argv[2] || 'ko,en').split(',')) {
  out[to] = out[to] || {}
  for (const t of all) if (!out[to][t] && same[to]?.(t)) out[to][t] = { t, src: to }
  const todo = all.filter((t) => !out[to][t])
  console.log(to, 'to translate:', todo.length, 'texts,', todo.join('').length, 'chars')
  for (let i = 0; i < todo.length; i += 20) {
    const chunk = todo.slice(i, i + 20)
    const res = await translate(chunk, to)
    chunk.forEach((t, k) => res[k] && (out[to][t] = res[k]))
  }
  console.log(to, Object.keys(out[to]).length, '/', all.length, 'saved')
}
writeFileSync(new URL('../server/tr-seed.js', import.meta.url), '// Generated by scripts/seed-translations.mjs — saved translations of the example content.\nexport default ' + JSON.stringify(out, null, 1) + '\n')
